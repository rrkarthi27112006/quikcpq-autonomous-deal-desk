"""
Professional Enterprise PDF Quote Generator for QuikCPQ Deal Desk Agent using fpdf2.
Outputs an executive, publication-grade B2B SaaS Quote with itemized breakdown,
financial guardrail compliance badge, and managerial authorization blocks.
"""
import io
from datetime import datetime
from typing import Dict, Any, List
from fpdf import FPDF

class CPQQuotePDF(FPDF):
    def __init__(self, quote_id: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.quote_id = quote_id
        self.set_auto_page_break(auto=True, margin=15)
        
    def header(self):
        # Corporate Top Accent Bar
        self.set_fill_color(30, 41, 59) # Slate 800
        self.rect(0, 0, 210, 8, "F")
        
        # Primary Brand Header
        self.set_y(12)
        self.set_font("helvetica", "B", 18)
        self.set_text_color(15, 23, 42) # Slate 900
        self.cell(100, 8, "QuikCPQ Solutions", ln=0, align="L")
        
        # Document Title / Reference
        self.set_font("helvetica", "B", 12)
        self.set_text_color(79, 70, 229) # Indigo 600
        self.cell(90, 8, f"OFFICIAL PROPOSAL #{self.quote_id}", ln=1, align="R")
        
        self.set_font("helvetica", "", 9)
        self.set_text_color(100, 116, 139) # Slate 500
        self.cell(100, 5, "Autonomous Deal Desk & Enterprise Quoting Infrastructure", ln=0, align="L")
        today_str = datetime.now().strftime("%B %d, %Y")
        self.cell(90, 5, f"Date: {today_str} | Valid for 30 Days", ln=1, align="R")
        
        # Horizontal Rule
        self.set_draw_color(226, 232, 240)
        self.set_line_width(0.4)
        self.line(10, 28, 200, 28)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("helvetica", "", 8)
        self.set_text_color(148, 163, 184)
        self.cell(95, 8, "Generated by QuikCPQ Autonomous Deal Desk Engine", align="L")
        self.cell(95, 8, f"Page {self.page_no()}/{{nb}}", align="R")

def generate_pdf_quote(data: Dict[str, Any]) -> bytes:
    """Generates an executive PDF quote and returns raw bytes."""
    quote_id = data.get("quote_id", "CPQ-DRAFT")
    pdf = CPQQuotePDF(quote_id)
    pdf.alias_nb_pages()
    pdf.add_page()
    
    # 1. Customer & Account Block
    company = data.get("customer_company", data.get("customer_name", "Enterprise Client"))
    contact = data.get("customer_name", "Procurement Officer")
    email = data.get("customer_email", "procurement@client.com")
    seats = data.get("seats", 1)
    base_tier_name = data.get("base_tier_name", "Enterprise")
    status = data.get("guardrail_status", "APPROVED")
    is_escalated = data.get("is_escalated", False)
    approval_type = data.get("approval_type", "auto")
    
    pdf.set_y(32)
    # Left Box: Prepared For
    pdf.set_fill_color(248, 250, 252) # Slate 50
    pdf.set_draw_color(226, 232, 240)
    pdf.rect(10, 32, 92, 34, "DF")
    
    pdf.set_xy(14, 35)
    pdf.set_font("helvetica", "B", 10)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(85, 5, "PREPARED FOR:", ln=1)
    
    pdf.set_x(14)
    pdf.set_font("helvetica", "B", 11)
    pdf.set_text_color(79, 70, 229)
    pdf.cell(85, 5, str(company)[:40], ln=1)
    
    pdf.set_x(14)
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(85, 5, f"Attention: {contact}", ln=1)
    pdf.set_x(14)
    pdf.cell(85, 5, f"Email: {email}", ln=1)
    
    # Right Box: Deal Status & Metadata
    pdf.rect(108, 32, 92, 34, "DF")
    pdf.set_xy(112, 35)
    pdf.set_font("helvetica", "B", 10)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(85, 5, "PROPOSAL STATUS & METRICS:", ln=1)
    
    pdf.set_x(112)
    pdf.set_font("helvetica", "B", 10)
    if status == "APPROVED":
        pdf.set_text_color(16, 185, 129) # Emerald
        badge_text = "STATUS: APPROVED / EXECUTIVE READY"
        if approval_type == "counter_offer_accepted":
            badge_text = "STATUS: APPROVED (COUNTER-OFFER)"
        elif approval_type == "manager_override":
            badge_text = "STATUS: APPROVED (MANAGER OVERRIDE)"
    else:
        pdf.set_text_color(245, 158, 11) # Amber
        badge_text = "STATUS: ESCALATED (PENDING HITL REVIEW)"
        
    pdf.cell(85, 5, badge_text, ln=1)
    
    pdf.set_x(112)
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(85, 5, f"Licensed Seats: {seats} Users ({base_tier_name} Tier)", ln=1)
    pdf.set_x(112)
    contract_term = "24 Months" if approval_type == "counter_offer_accepted" else "12 Months (Annual)"
    pdf.cell(85, 5, f"Contract Term: {contract_term} | Billing: Annual Advance", ln=1)
    
    pdf.ln(8)
    
    # 2. Dependency Fix Notice if applicable
    fixes = data.get("dependency_fixes", [])
    if fixes:
        pdf.set_y(70)
        pdf.set_fill_color(238, 242, 255) # Indigo 50
        pdf.set_draw_color(199, 210, 254) # Indigo 200
        pdf.rect(10, 70, 190, 12, "DF")
        pdf.set_xy(14, 71.5)
        pdf.set_font("helvetica", "B", 8.5)
        pdf.set_text_color(67, 56, 202)
        fix_msg = f"ARCHITECTURAL AUTO-CORRECTION: {fixes[0]['action']}"
        pdf.cell(182, 4.5, fix_msg[:110], ln=1)
        pdf.set_x(14)
        pdf.set_font("helvetica", "", 8)
        pdf.set_text_color(79, 70, 229)
        pdf.cell(182, 4, "Enterprise SSO requires Pro or Enterprise tier. Configuration automatically upgraded to maintain SLA compliance.", ln=1)
        pdf.set_y(86)
    else:
        pdf.set_y(72)
        
    # 3. Itemized Quote Table
    pdf.set_font("helvetica", "B", 10)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(190, 6, "ITEMIZED PRODUCT & SERVICE BREAKDOWN", ln=1)
    
    # Table Header
    pdf.set_fill_color(241, 245, 249) # Slate 100
    pdf.set_draw_color(203, 213, 225)
    pdf.set_font("helvetica", "B", 8.5)
    pdf.set_text_color(51, 65, 85)
    
    col_w = [70, 25, 25, 35, 35]
    headers = ["Item / Module Description", "Quantity", "Unit Price", "Monthly Subtotal", "Annual Subtotal"]
    
    for i in range(len(headers)):
        align = "L" if i == 0 else "R"
        pdf.cell(col_w[i], 7, headers[i], border=1, align=align, fill=True)
    pdf.ln()
    
    # Table Rows
    line_items: List[Dict[str, Any]] = data.get("line_items", [])
    pdf.set_font("helvetica", "", 8.5)
    pdf.set_text_color(30, 41, 59)
    
    for item in line_items:
        name = str(item.get("name", "Module"))
        qty = str(item.get("quantity", 1))
        unit_p = f"${item.get('unit_price', 0):,.2f}"
        monthly = f"${item.get('subtotal_monthly', 0):,.2f}"
        annual = f"${item.get('subtotal_annual', 0):,.2f}"
        
        pdf.cell(col_w[0], 6.5, name[:42], border=1, align="L")
        pdf.cell(col_w[1], 6.5, qty, border=1, align="R")
        pdf.cell(col_w[2], 6.5, unit_p, border=1, align="R")
        pdf.cell(col_w[3], 6.5, monthly, border=1, align="R")
        pdf.cell(col_w[4], 6.5, annual, border=1, align="R")
        pdf.ln()
        
    pdf.ln(3)
    
    # 4. Financial Summary Grid
    list_monthly = data.get("list_price_monthly", 0.0)
    list_annual = data.get("list_price_annual", 0.0)
    discount_pct = data.get("applied_discount_pct", data.get("final_discount_pct", 0.0))
    discount_monthly = data.get("discount_amount_monthly", list_monthly * (discount_pct / 100.0))
    discount_annual = discount_monthly * 12
    net_monthly = data.get("net_price_monthly", 0.0)
    net_annual = data.get("net_price_annual", 0.0)
    gross_margin = data.get("gross_margin_pct", 0.0)
    
    # Financial summary on right side
    summary_x = 105
    label_w = 55
    val_w = 40
    
    pdf.set_x(summary_x)
    pdf.set_font("helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(label_w, 6, "Gross List Price (Monthly):", align="R")
    pdf.set_font("helvetica", "B", 9)
    pdf.cell(val_w, 6, f"${list_monthly:,.2f}", align="R", ln=1)
    
    pdf.set_x(summary_x)
    pdf.set_font("helvetica", "", 9)
    pdf.cell(label_w, 6, f"Applied Discount ({discount_pct:.1f}%):", align="R")
    pdf.set_font("helvetica", "B", 9)
    pdf.set_text_color(220, 38, 38) # Red for discount deduction
    pdf.cell(val_w, 6, f"-${discount_monthly:,.2f}", align="R", ln=1)
    
    # Net Total Highlight Box
    pdf.set_x(summary_x)
    pdf.set_fill_color(240, 253, 244) # Green 50
    pdf.set_draw_color(187, 247, 208)
    pdf.rect(summary_x, pdf.get_y(), 95, 14, "DF")
    
    pdf.set_xy(summary_x + 2, pdf.get_y() + 1.5)
    pdf.set_font("helvetica", "B", 10)
    pdf.set_text_color(22, 101, 52) # Green 800
    pdf.cell(label_w - 2, 5, "Net Monthly Investment:", align="L")
    pdf.cell(val_w, 5, f"${net_monthly:,.2f}/mo", align="R", ln=1)
    
    pdf.set_x(summary_x + 2)
    pdf.set_font("helvetica", "B", 10.5)
    pdf.cell(label_w - 2, 5, "Total Annual Commitment:", align="L")
    pdf.cell(val_w, 5, f"${net_annual:,.2f}/yr", align="R", ln=1)
    
    # 5. Guardrail Audit & Compliance Stamp Box (Left side of summary)
    stamp_y = pdf.get_y() - 17
    pdf.set_fill_color(248, 250, 252)
    pdf.set_draw_color(226, 232, 240)
    pdf.rect(10, stamp_y, 88, 26, "DF")
    
    pdf.set_xy(13, stamp_y + 2)
    pdf.set_font("helvetica", "B", 8.5)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(82, 4, "AUDIT & GOVERNANCE COMPLIANCE", ln=1)
    
    pdf.set_x(13)
    pdf.set_font("helvetica", "", 7.5)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(82, 3.5, f"Verified Margin Floor: {gross_margin:.1f}% (Policy Minimum: 25.0%)", ln=1)
    pdf.set_x(13)
    pdf.cell(82, 3.5, f"Discount Threshold: {discount_pct:.1f}% (Auto-Approval Max: 15.0%)", ln=1)
    pdf.set_x(13)
    stamp_text = "Governance Status: COMPLIANT & APPROVED" if status == "APPROVED" else "Governance Status: HITL ESCALATION ACTIVE"
    pdf.cell(82, 3.5, stamp_text, ln=1)
    pdf.set_x(13)
    pdf.cell(82, 3.5, f"Audit Log ID: {quote_id} | Engine: QuikCPQ Multi-Agent v2.4", ln=1)
    
    pdf.ln(12)
    
    # 6. Terms & Execution Block
    pdf.set_y(pdf.get_y() + 8)
    pdf.set_font("helvetica", "B", 9)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(190, 5, "COMMERCIAL TERMS & SIGNATURE ACCEPTANCE", ln=1)
    
    pdf.set_font("helvetica", "", 7.5)
    pdf.set_text_color(100, 116, 139)
    terms_text = (
        "1. Invoicing: Annual advance billing with Net 30 payment terms. "
        "2. Service Level Agreement: 99.95% operational uptime with dedicated response SLAs. "
        "3. Pricing Protection: The rates quoted above remain locked for the duration of the executed term. "
        "4. Acceptance: Signature below constitutes a binding agreement under QuikCPQ Master Services Agreement v4.2."
    )
    pdf.multi_cell(190, 3.5, terms_text)
    pdf.ln(4)
    
    # Signature Lines
    sig_y = pdf.get_y() + 2
    pdf.set_draw_color(148, 163, 184)
    pdf.line(10, sig_y + 12, 90, sig_y + 12)
    pdf.line(110, sig_y + 12, 190, sig_y + 12)
    
    pdf.set_xy(10, sig_y + 13)
    pdf.set_font("helvetica", "B", 8)
    pdf.set_text_color(71, 85, 105)
    pdf.cell(80, 4, f"Authorized Client Signature ({company[:30]})", ln=0)
    pdf.set_x(110)
    pdf.cell(80, 4, "QuikCPQ Deal Desk Manager Approval Stamp", ln=1)
    
    pdf.set_xy(10, sig_y + 17)
    pdf.set_font("helvetica", "", 7.5)
    pdf.cell(80, 4, "Date: ________________________", ln=0)
    pdf.set_x(110)
    pdf.cell(80, 4, f"Electronically Verified & Signed: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", ln=1)

    return bytes(pdf.output())
